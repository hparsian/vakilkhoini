// تبدیل اعداد انگلیسی به فارسی با کامای سه‌رقمی
export function formatPersianNumber(num) {
  if (num === null || num === undefined || isNaN(num)) return '۰'
  const rounded = Math.round(Number(num))
  const parts = rounded.toString().replace(/\B(?=(\d{3})+(?!\d))/g, '،')
  const farsiDigits = ['۰', '۱', '۲', '۳', '۴', '۵', '۶', '۷', '۸', '۹']
  return parts.replace(/\d/g, (x) => farsiDigits[x])
}

// تمیزکاری ورودی کاربر به عدد انگلیسی
export function parseNumberInput(val) {
  if (!val) return 0
  const normalized = String(val)
    .replace(/[۰-۹]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'.indexOf(d))
    .replace(/[^0-9]/g, '')
  return Number(normalized) || 0
}
